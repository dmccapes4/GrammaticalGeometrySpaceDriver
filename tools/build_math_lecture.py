#!/usr/bin/env python3
"""
build_math_lecture.py — deterministic whole-Matthew math-lecture pass.

Pipeline (docs/GAMEPLAN_MORPHGNT_CADENCE_GRAMMATION_20261112.md):
  punctuation cadence (script) -> math-lecture verse identification ->
  explicit mathematical translation (script) -> MorphGNT-required word
  identification -> MorphGNT graded against cadence and grammation.

No model calls. Outputs:
  tools/math_lecture/matthew_cadence_math.json   (machine record, all verses)
  tools/math_lecture/MATTHEW_MATH_LECTURE.md     (letter math applied to
                                                  the gated verses)
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sources import load_morphgnt, morphgnt_verse_tokens
from punctuation import tokenise_morph_tokens, cadence_map, mark_counts
from math_layer import math_for_verse
from grammations import corpus_stats, morphgnt_need, grade_morphgnt_word

MORPH = ROOT / "morphgnt" / "sblgnt" / "61-Mt-morphgnt.txt"
OUT_DIR = ROOT / "tools" / "math_lecture"


def main() -> int:
    data = load_morphgnt(MORPH)
    stats = corpus_stats(data)
    verses_out = []
    need_counter: Counter = Counter()
    grade_counter: Counter = Counter()
    n_math_lecture = 0
    n_grammation_words = 0
    md = ["# Matthew — Math Lecture Pass (script, proposed)",
          "",
          "Generated by `tools/build_math_lecture.py` from SBLGNT via "
          "MorphGNT field 3/4. Deterministic; no model calls. Every math "
          "reading is `status: proposed`; nothing here eliminates a "
          "lexical reading. Letter table: suggested v0.1 "
          "(`grammations.py`).",
          ""]

    for (ch, vs) in sorted(data):
        ref = f"Matthew {ch}:{vs}"
        morph_words = morphgnt_verse_tokens(data, ch, vs)
        toks = tokenise_morph_tokens(morph_words)
        vm = math_for_verse(toks, ref, morph_stats=stats)
        lecture = vm["math_lecture"]
        if lecture["is_math_lecture"]:
            n_math_lecture += 1
        n_grammation_words += len(vm["grammations"])

        words_out = []
        for i, w in enumerate(morph_words):
            need = morphgnt_need(w, stats)
            for r in need:
                need_counter[r] += 1
            gram = vm["grammations"].get(str(i))
            grade = grade_morphgnt_word(w, need, toks[i], gram)
            grade_counter[grade["grade_offline"]] += 1
            words_out.append({
                "index": i, "surface": w["word"], "lemma": w["lemma"],
                "pos": w["pos"], "parse_code": w["parse"],
                "morphgnt_need": need, "grade_offline": grade["grade_offline"],
                "grammations": bool(gram),
            })

        verses_out.append({
            "verse_ref": ref, "chapter": ch, "verse": vs,
            "mark_counts": mark_counts(toks),
            "cadence_map": cadence_map(toks),
            "math_lecture": lecture,
            "explicit_math_translation": vm["explicit_math_translation"],
            "grammations": vm["grammations"],
            "words": words_out,
        })

        # Human document: gated verses get full letter math (V1 automatic).
        if vm["gates"]:
            md.append(f"## {ref}")
            md.append("")
            for line in vm["explicit_math_translation"][1:]:
                md.append(f"- {line}")
            md.append("")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    census = {
        "verses": len(verses_out),
        "math_lecture_verses": n_math_lecture,
        "gated_verses": sum(1 for v in verses_out
                            if v["mark_counts"].get("gate", 0) > 0),
        "grammation_words": n_grammation_words,
        "morphgnt_need_reasons": dict(need_counter),
        "grade_counts_offline": dict(grade_counter),
        "note": "grades are offline (vs cadence/grammation); Logeion is "
                "the runtime second witness in Qwen runs",
    }
    (OUT_DIR / "matthew_cadence_math.json").write_text(json.dumps(
        {"census": census, "verses": verses_out},
        ensure_ascii=False, indent=1), encoding="utf-8")
    header = [f"Census: {census['verses']} verses; "
              f"{census['gated_verses']} gated; "
              f"{census['math_lecture_verses']} math-lecture; "
              f"{census['grammation_words']} words letter-parsed. "
              f"Grades (offline): {dict(grade_counter)}. "
              f"MorphGNT-need reasons: {dict(need_counter)}.",
              ""]
    (OUT_DIR / "MATTHEW_MATH_LECTURE.md").write_text(
        "\n".join(md[:4] + header + md[4:]), encoding="utf-8")

    print(json.dumps(census, ensure_ascii=False, indent=2))
    print(f"-> {OUT_DIR / 'matthew_cadence_math.json'}")
    print(f"-> {OUT_DIR / 'MATTHEW_MATH_LECTURE.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
